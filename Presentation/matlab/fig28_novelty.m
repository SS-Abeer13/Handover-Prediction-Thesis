function fig28_novelty()
%FIG28  Every method is borrowed on purpose; the novelty is where each is pointed.
S = fig_style();
newfig(1480, 780); hold on;
axis([0 100 0 100]); axis off;

xa = 2.5; xb = 26; xc = 53;

% header
text(xa, 95, 'COMPONENT', 'FontSize', 13, 'FontWeight', 'bold', 'Color', S.grey, 'FontName', 'Arial');
text(xb, 95, 'BORROWED FROM', 'FontSize', 13, 'FontWeight', 'bold', 'Color', S.grey, 'FontName', 'Arial');
text(xc, 95, 'WHAT IS NEW HERE', 'FontSize', 13, 'FontWeight', 'bold', 'Color', S.maroon, 'FontName', 'Arial');
plot([xa 98], [91.5 91.5], '-', 'Color', [0.75 0.75 0.75], 'LineWidth', 1.2);

comp = {'Discrete-time survival', 'Conformal risk control', 'Self-exciting point process', ...
        'Grouped cross-validation', 'Signalling decoding', 'Unsupervised adaptation'};
from = {'Wiegrebe et al. 2024 (review)', 'Angelopoulos et al. 2024;', ...
        'Hawkes 1971; Ogata 1988', 'standard ML practice', 'Deng et al. 2018 (IMC)', ...
        'Sun and Saenko 2016 (CORAL)'};
from2 = {'', 'Cohen 2022, Simeone 2025 in wireless', '', '', '', ''};
newc = {{'Pointed at handover: horizon coherence by identity,', ...
         'for any learner - 0% violations against 43.6%'}, ...
        {'The exchangeable unit is the DRIVE, not the sample,', ...
         'giving a campaign-design rule:  n \geq 1/\alpha - 1'}, ...
        {'A branching ratio for handover arrivals - 0.605,', ...
         'stable over four captures, with its kernel residual-tested'}, ...
        {'Measured what it is worth on drive-test radio:', ...
         '+4% to +74%, and architecture-dependent, so it reorders'}, ...
        {'A configuration timeline for message-scoped measId;', ...
         'the deployed offsets are negative, not the assumed +3 dB'}, ...
        {'Reported as a measured negative rather than omitted,', ...
         'and matched against a nine-method published benchmark'}};

y = 85;
for i = 1:6
    text(xa, y, comp{i}, 'FontSize', 14.5, 'Color', S.ink, 'FontName', 'Arial', ...
         'FontWeight', 'bold', 'VerticalAlignment', 'middle');
    if isempty(from2{i})
        text(xb, y, from{i}, 'FontSize', 13, 'Color', S.grey, 'FontName', 'Arial', ...
             'VerticalAlignment', 'middle');
    else
        text(xb, y + 2.4, from{i}, 'FontSize', 13, 'Color', S.grey, 'FontName', 'Arial', ...
             'VerticalAlignment', 'middle');
        text(xb, y - 2.4, from2{i}, 'FontSize', 13, 'Color', S.grey, 'FontName', 'Arial', ...
             'VerticalAlignment', 'middle');
    end
    text(xc, y + 2.4, newc{i}{1}, 'FontSize', 13.5, 'Color', S.maroon, 'FontName', 'Arial', ...
         'VerticalAlignment', 'middle');
    text(xc, y - 2.4, newc{i}{2}, 'FontSize', 13.5, 'Color', S.maroon, 'FontName', 'Arial', ...
         'VerticalAlignment', 'middle');
    y = y - 13.6;
end

plot([xa 98], [5.5 5.5], '-', 'Color', [0.75 0.75 0.75], 'LineWidth', 1.2);
text(xa, 1.8, ['Two tasks fall out of the signalling that the literature has not posed: ' ...
     'report conversion, and a ping-pong rate whose definition is stated.'], ...
     'FontSize', 13.5, 'Color', S.ink, 'FontName', 'Arial', 'FontAngle', 'italic');

savefig_png('fig28_novelty');
end
